/** WCAG relative luminance and "which text colour goes on this accent". Pure, no DOM. */

export function parseHex(hex: string): [number, number, number] | null {
  const m = /^#([0-9a-f]{6})$/i.exec(hex.trim());
  if (!m) return null;
  const n = parseInt(m[1]!, 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
}

export function luminance([r, g, b]: [number, number, number]): number {
  const lin = (v: number) => {
    const c = v / 255;
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  };
  return 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b);
}

export function contrastRatio(a: number, b: number): number {
  const [hi, lo] = a > b ? [a, b] : [b, a];
  return (hi + 0.05) / (lo + 0.05);
}

/** White if it reaches 4.5:1 on the accent, otherwise black. */
export function onAccent(hex: string): '#ffffff' | '#000000' {
  const rgb = parseHex(hex);
  if (!rgb) return '#ffffff';
  return contrastRatio(1, luminance(rgb)) >= 4.5 ? '#ffffff' : '#000000';
}
